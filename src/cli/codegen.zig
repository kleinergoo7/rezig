//! `rezig codegen`: emit Zig for selected guest functions.

const std = @import("std");
const Io = std.Io;
const parse = @import("parse.zig");
const image = @import("../xex/image.zig");
const analyze = @import("../ppc/analyze.zig");
const slice = @import("../codegen/slice.zig");
const emit = @import("../codegen/emit.zig");
const abi = @import("../codegen/abi.zig");

pub const Options = parse.Codegen;

pub const header =
    \\// Generated by rezig. Do not edit.
    \\
    \\const std = @import("std");
    \\const Ctx = @import("rezig_runtime").ctx.Ctx;
    \\
    \\
;

pub fn run(allocator: std.mem.Allocator, io: Io, opts: Options, key: ?[16]u8) !void {
    const xex_path = if (opts.xex) |p|
        try allocator.dupe(u8, p)
    else
        try std.fmt.allocPrint(allocator, "{s}/default.xex", .{opts.tree.?});
    defer allocator.free(xex_path);

    var img = try image.load(allocator, io, xex_path, key);
    defer img.deinit(allocator);

    const sections = try allocator.alloc(analyze.CodeSection, img.sections.len);
    defer allocator.free(sections);
    var count: usize = 0;
    for (img.sections) |s| {
        if (!img.isExecutable(s)) continue;
        sections[count] = .{ .addr = img.base_address + s.virtual_address, .bytes = img.sectionBytes(s) };
        count += 1;
    }

    const wanted = if (opts.slice_list) |path|
        @as(u32, @intCast((try slice.readAddressList(allocator, io, path)).len))
    else
        opts.slice.?;

    var picked: []slice.Candidate = undefined;
    if (opts.slice_list) |path| {
        const addrs = try slice.readAddressList(allocator, io, path);
        defer allocator.free(addrs);
        picked = try allocator.alloc(slice.Candidate, addrs.len);
        for (addrs, 0..) |addr, i| {
            var err_addr: u32 = 0;
            picked[i] = .{ .addr = addr, .words = try analyze.functionAt(allocator, sections[0..count], addr, &err_addr) };
        }
    } else {
        picked = try slice.select(allocator, sections[0..count], img.entry_point, wanted);
    }
    defer allocator.free(picked);

    var out = std.ArrayList(u8).empty;
    defer out.deinit(allocator);
    try out.appendSlice(allocator, header);
    for (picked, 0..) |candidate, i| {
        if (i != 0) try out.append(allocator, '\n');
        const text = try emit.function(allocator, candidate.words, .{ .addr = candidate.addr });
        defer allocator.free(text);
        try out.appendSlice(allocator, text);
    }

    for (picked) |candidate| {
        try out.print(allocator, "const w_{X} = [_]u32{{\n", .{candidate.addr});
        for (candidate.words, 0..) |word, i| {
            if (i % 4 == 0) try out.appendSlice(allocator, "    ");
            try out.print(allocator, "0x{X}", .{word});
            if (i + 1 == candidate.words.len) {
                try out.appendSlice(allocator, ",\n");
            } else if (i % 4 == 3) {
                try out.appendSlice(allocator, ",\n");
            } else {
                try out.appendSlice(allocator, ", ");
            }
        }
        try out.appendSlice(allocator, "};\n");
    }
    try out.appendSlice(allocator, "\npub const functions = [_]struct { addr: u32, words: []const u32 }{\n");
    for (picked) |candidate| {
        try out.print(allocator, "    .{{ .addr = 0x{X}, .words = &w_{X} }},\n", .{ candidate.addr, candidate.addr });
    }
    try out.appendSlice(allocator, "};\n\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
    for (picked) |candidate| {
        var name_buf: [10]u8 = undefined;
        try out.print(allocator, "        0x{X} => {{\n            {s}(ctx);\n            return true;\n        }},\n", .{ candidate.addr, abi.fnName(candidate.addr, &name_buf) });
    }
    try out.appendSlice(allocator, "        else => false,\n    };\n}\n");

    var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
    defer dir.close(io);
    var atomic = try dir.createFileAtomic(io, "slice.zig", .{ .replace = true });
    defer atomic.deinit(io);
    try atomic.file.writeStreamingAll(io, out.items);
    try atomic.replace(io);

    var addr_list = try allocator.alloc(u32, picked.len);
    defer allocator.free(addr_list);
    for (picked, 0..) |candidate, i| addr_list[i] = candidate.addr;
    var list_buf: [512]u8 = undefined;
    const list_path = try std.fmt.bufPrint(&list_buf, "{s}/addresses.json", .{opts.out});
    try slice.writeAddressList(allocator, io, list_path, addr_list);

    var buf: [256]u8 = undefined;
    var writer = Io.File.stdout().writer(io, &buf);
    try writer.interface.print("emitted {d} functions to {s}/slice.zig\n", .{ picked.len, opts.out });
    try writer.interface.flush();
}
