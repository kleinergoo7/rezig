//! `rezig codegen`: emit Zig for selected guest functions.

const std = @import("std");
const Io = std.Io;
const parse = @import("parse.zig");
const input = @import("input.zig");
const analyze = @import("../ppc/analyze.zig");
const slice = @import("../codegen/slice.zig");
const xextool = @import("xextool");
const emit = @import("../codegen/emit.zig");
const abi = @import("../codegen/abi.zig");

pub const Options = parse.Codegen;

pub const header =
    \\// Generated by rezig. Do not edit.
    \\
    \\const std = @import("std");
    \\const Ctx = @import("rezig_runtime").ctx.Ctx;
    \\
    \\
;

pub fn run(allocator: std.mem.Allocator, io: Io, opts: Options, key: ?[16]u8) !void {
    var loaded = try input.load(allocator, io, opts.tree, opts.xex, opts.elf, key);
    defer loaded.deinit(allocator);
    const img = &loaded.image;

    const sections = try allocator.alloc(analyze.CodeSection, img.sections.len);
    defer allocator.free(sections);
    var count: usize = 0;
    for (img.sections) |s| {
        if (!img.isExecutable(s)) continue;
        sections[count] = .{ .addr = img.base_address + s.virtual_address, .bytes = img.sectionBytes(s) };
        count += 1;
    }

    const found = try analyze.functionsFrom(allocator, sections[0..count], img.entry_point, loaded.seeds);
    defer analyze.freeFunctions(allocator, found);

    var picked: []slice.Candidate = undefined;
    if (opts.slice_list) |path| {
        const addrs = try slice.readAddressList(allocator, io, path);
        defer allocator.free(addrs);
        picked = try allocator.alloc(slice.Candidate, addrs.len);
        var done: usize = 0;
        errdefer {
            for (picked[0..done]) |candidate| allocator.free(candidate.words);
            allocator.free(picked);
        }
        for (addrs, 0..) |addr, i| {
            var err_addr: u32 = 0;
            picked[i] = .{ .addr = addr, .words = try analyze.functionAt(allocator, sections[0..count], addr, &err_addr) };
            done += 1;
        }
    } else if (opts.all == true) {
        var list: std.ArrayList(slice.Candidate) = .empty;
        errdefer {
            for (list.items) |c| allocator.free(c.words);
            list.deinit(allocator);
        }
        var skipped: usize = 0;
        var failed: usize = 0;
        for (found) |f| {
            if (f.words.len == 0 or f.words.len > analyze.max_function_insns) {
                std.debug.print("codegen skip addr 0x{X}: bad length {d}\n", .{ f.addr, f.words.len });
                skipped += 1;
                continue;
            }
            if (!emit.supportsAll(f.addr, f.words)) {
                std.debug.print("codegen skip addr 0x{X}: unsupported\n", .{f.addr});
                skipped += 1;
                continue;
            }
            const words = try allocator.dupe(u32, f.words);
            errdefer allocator.free(words);
            const text = emit.function(allocator, words, .{ .addr = f.addr, .external_dispatch = true }) catch |e| {
                std.debug.print("codegen fail addr 0x{X}: {s}\n", .{ f.addr, @errorName(e) });
                allocator.free(words);
                failed += 1;
                continue;
            };
            allocator.free(text);
            try list.append(allocator, .{ .addr = f.addr, .words = words });
        }
        if (skipped + failed != 0) {
            std.debug.print("codegen --all: {d} skipped, {d} failed, {d} emitted; refusing partial output\n", .{ skipped, failed, list.items.len });
            return error.IncompleteCodegen;
        }
        picked = try list.toOwnedSlice(allocator);
    } else {
        const wanted = opts.slice orelse return error.MissingOption;
        picked = try slice.select(allocator, sections[0..count], img.entry_point, wanted, loaded.seeds);
    }
    defer {
        for (picked) |candidate| allocator.free(candidate.words);
        allocator.free(picked);
    }

    if (opts.all == true) {
        const chunk_size: usize = 1000;
        var chunks: std.ArrayList([]const u8) = .empty;
        defer {
            for (chunks.items) |c| allocator.free(c);
            chunks.deinit(allocator);
        }

        var i: usize = 0;
        var index: usize = 0;
        while (i < picked.len) {
            const end = @min(i + chunk_size, picked.len);
            const chunk = picked[i..end];

            var out = std.ArrayList(u8).empty;
            errdefer out.deinit(allocator);
            try out.appendSlice(allocator, header);
            for (chunk, 0..) |candidate, j| {
                if (j != 0) try out.append(allocator, '\n');
                const text = try emit.function(allocator, candidate.words, .{ .addr = candidate.addr, .external_dispatch = true });
                defer allocator.free(text);
                try out.appendSlice(allocator, text);
            }
            try out.appendSlice(allocator, "\npub fn chunk_dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
            for (chunk) |candidate| {
                var name_buf: [10]u8 = undefined;
                try out.print(allocator, "        0x{X} => {{\n            {s}(ctx);\n            return true;\n        }},\n", .{
                    candidate.addr, abi.fnName(candidate.addr, &name_buf),
                });
            }
            try out.appendSlice(allocator, "        else => false,\n    };\n}\n");

            const name = try std.fmt.allocPrint(allocator, "chunk_{d:0>3}.zig", .{index});
            defer allocator.free(name);
            var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
            defer dir.close(io);
            var atomic = try dir.createFileAtomic(io, name, .{ .replace = true });
            defer atomic.deinit(io);
            try atomic.file.writeStreamingAll(io, out.items);
            try atomic.replace(io);
            out.deinit(allocator);

            const owned = try allocator.dupe(u8, name);
            try chunks.append(allocator, owned);

            i = end;
            index += 1;
        }

        var central = std.ArrayList(u8).empty;
        defer central.deinit(allocator);
        try central.appendSlice(allocator, "const std = @import(\"std\");\n");
        try central.appendSlice(allocator, "const Ctx = @import(\"rezig_runtime\").ctx.Ctx;\n\n");
        for (chunks.items, 0..) |name, ci| {
            try central.print(allocator, "const chunk_{d:0>3} = @import(\"{s}\");\n", .{ ci, name });
        }
        // Import thunks live in the tail of `.text`, so a chunk must not claim
        // a thunk address before the kernel switch sees it.
        try central.appendSlice(allocator, "\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n    if (@import(\"kernel.zig\").dispatch(addr, ctx)) return true;\n");
        for (chunks.items, 0..) |_, ci| {
            try central.print(allocator, "    if (chunk_{d:0>3}.chunk_dispatch(addr, ctx)) return true;\n", .{ci});
        }
        try central.appendSlice(allocator, "    return false;\n}\n\npub fn init(ctx: *Ctx, cell_base: u32) void {\n    @import(\"kernel.zig\").init(ctx, cell_base);\n}\n");

        var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
        defer dir.close(io);
        var atomic = try dir.createFileAtomic(io, "dispatch.zig", .{ .replace = true });
        defer atomic.deinit(io);
        try atomic.file.writeStreamingAll(io, central.items);
        try atomic.replace(io);

        // Import thunks become host stubs that log on first call. The same
        // table patches the IAT slots: a function slot points at its thunk,
        // a data slot points at a guest cell the guest can dereference.
        const ImportEntry = struct {
            slot: u32,
            thunk: u32,
            name: []const u8,
            ordinal: u16,
            is_variable: bool,
        };
        var imports: std.ArrayList(ImportEntry) = .empty;
        defer {
            for (imports.items) |entry| allocator.free(entry.name);
            imports.deinit(allocator);
        }
        if (!loaded.is_elf) {
            // Import tables live in the unencrypted header. A key is only needed
            // when the payload is encrypted; `image.load` already handled that.
            const import_key = key orelse std.mem.zeroes([16]u8);
            const import_path = if (opts.xex) |p|
                try allocator.dupe(u8, p)
            else
                try std.fmt.allocPrint(allocator, "{s}/default.xex", .{opts.tree.?});
            defer allocator.free(import_path);
            const raw = Io.Dir.cwd().readFileAlloc(io, import_path, allocator, .limited(1 << 40)) catch null;
            if (raw) |bytes| {
                defer allocator.free(bytes);
                var xex = xextool.xex.model.Xex.init(allocator);
                defer xex.deinit();
                const keys = xextool.xex.keys.Keys.uniform(import_key);
                _ = xextool.xex.reader.readBytes(&xex, bytes, keys) catch |e| {
                    std.debug.print("codegen: import table of {s} unreadable: {s}\n", .{ import_path, @errorName(e) });
                    return e;
                };
                for (xex.import_libraries.items) |lib| {
                    const name = std.mem.sliceTo(&lib.name, 0);
                    // Records mix two kinds of guest word. An import descriptor
                    // lives in the IAT and has a zero high byte; a thunk stub
                    // starts with 0x01_00_ORD. A function import has a thunk
                    // with the same ordinal, a data import has none.
                    for (lib.addresses, 0..) |slot, record| {
                        if (slot == 0) continue;
                        const word = try importWord(img, slot, name, record);
                        if (word >> 24 != 0) continue;
                        const ordinal: u16 = @truncate(word);
                        const thunk = try matchingThunk(img, lib.addresses, ordinal, name);
                        try imports.append(allocator, .{
                            .slot = slot,
                            .thunk = thunk,
                            .name = try allocator.dupe(u8, name),
                            .ordinal = ordinal,
                            .is_variable = thunk == 0,
                        });
                    }
                }
            }
        }

        var kernel = std.ArrayList(u8).empty;
        defer kernel.deinit(allocator);
        try kernel.appendSlice(allocator, "const std = @import(\"std\");\nconst Ctx = @import(\"rezig_runtime\").ctx.Ctx;\n\nfn logImport(comptime name: []const u8, comptime index: u16, ctx: *const Ctx) void {\n    std.debug.print(\"import {s}[0x{X}] lr=0x{X} r3=0x{X} r4=0x{X} r5=0x{X} r6=0x{X}\\n\", .{ name, index, ctx.lr, ctx.gpr[3], ctx.gpr[4], ctx.gpr[5], ctx.gpr[6] });\n}\n\npub fn init(ctx: *Ctx, cell_base: u32) void {\n    var cell = cell_base;\n    _ = &cell;\n");
        for (imports.items) |entry| {
            if (entry.is_variable) {
                try kernel.print(allocator, "    // {f}[0x{X}] is data: dereferenceable guest cell\n    ctx.store32(0x{X}, cell);\n    ctx.store32(cell, 0);\n    cell += 4;\n", .{
                    std.zig.fmtString(entry.name), entry.ordinal, entry.slot,
                });
            } else {
                try kernel.print(allocator, "    // {f}[0x{X}] is a function: point at its thunk\n    ctx.store32(0x{X}, 0x{X});\n", .{
                    std.zig.fmtString(entry.name), entry.ordinal, entry.slot, entry.thunk,
                });
            }
        }
        try kernel.appendSlice(allocator, "    @import(\"rezig_runtime\").kernel.initThread(ctx);\n}\n\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
        for (imports.items) |entry| {
            if (entry.thunk != 0) try kernelCase(allocator, &kernel, entry.thunk, entry.name, entry.ordinal);
        }
        // Thunk switch: unknown addresses fall through to chunk dispatch.
        try kernel.appendSlice(allocator, "        else => false,\n    };\n}\n");
        var kernel_atomic = try dir.createFileAtomic(io, "kernel.zig", .{ .replace = true });
        defer kernel_atomic.deinit(io);
        try kernel_atomic.file.writeStreamingAll(io, kernel.items);
        try kernel_atomic.replace(io);

        var addr_list = try allocator.alloc(u32, picked.len);
        defer allocator.free(addr_list);
        for (picked, 0..) |candidate, j| addr_list[j] = candidate.addr;
        var list_buf: [512]u8 = undefined;
        const list_path = try std.fmt.bufPrint(&list_buf, "{s}/addresses.json", .{opts.out});
        try slice.writeAddressList(allocator, io, list_path, addr_list);

        var buf: [256]u8 = undefined;
        var writer = Io.File.stdout().writer(io, &buf);
        try writer.interface.print("emitted {d} functions in {d} chunks to {s}\n", .{ picked.len, chunks.items.len, opts.out });
        try writer.interface.flush();
        return;
    }

    var out = std.ArrayList(u8).empty;
    defer out.deinit(allocator);
    try out.appendSlice(allocator, header);
    for (picked, 0..) |candidate, i| {
        if (i != 0) try out.append(allocator, '\n');
        const text = try emit.function(allocator, candidate.words, .{ .addr = candidate.addr });
        defer allocator.free(text);
        try out.appendSlice(allocator, text);
    }

    for (picked) |candidate| {
        try out.print(allocator, "const w_{X} = [_]u32{{\n", .{candidate.addr});
        for (candidate.words, 0..) |word, i| {
            if (i % 4 == 0) try out.appendSlice(allocator, "    ");
            try out.print(allocator, "0x{X}", .{word});
            if (i + 1 == candidate.words.len) {
                try out.appendSlice(allocator, ",\n");
            } else if (i % 4 == 3) {
                try out.appendSlice(allocator, ",\n");
            } else {
                try out.appendSlice(allocator, ", ");
            }
        }
        try out.appendSlice(allocator, "};\n");
    }
    try out.appendSlice(allocator, "\npub const functions = [_]struct { addr: u32, words: []const u32 }{\n");
    for (picked) |candidate| {
        try out.print(allocator, "    .{{ .addr = 0x{X}, .words = &w_{X} }},\n", .{ candidate.addr, candidate.addr });
    }
    try out.appendSlice(allocator, "};\n\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
    for (picked) |candidate| {
        var name_buf: [10]u8 = undefined;
        try out.print(allocator, "        0x{X} => {{\n            {s}(ctx);\n            return true;\n        }},\n", .{ candidate.addr, abi.fnName(candidate.addr, &name_buf) });
    }
    try out.appendSlice(allocator, "        else => false,\n    };\n}\n");

    var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
    defer dir.close(io);
    var atomic = try dir.createFileAtomic(io, "slice.zig", .{ .replace = true });
    defer atomic.deinit(io);
    try atomic.file.writeStreamingAll(io, out.items);
    try atomic.replace(io);

    var addr_list = try allocator.alloc(u32, picked.len);
    defer allocator.free(addr_list);
    for (picked, 0..) |candidate, i| addr_list[i] = candidate.addr;
    var list_buf: [512]u8 = undefined;
    const list_path = try std.fmt.bufPrint(&list_buf, "{s}/addresses.json", .{opts.out});
    try slice.writeAddressList(allocator, io, list_path, addr_list);

    var buf: [256]u8 = undefined;
    var writer = Io.File.stdout().writer(io, &buf);
    try writer.interface.print("emitted {d} functions to {s}/slice.zig\n", .{ picked.len, opts.out });
    try writer.interface.flush();
}

/// Reads an import record's first word from the loaded image. Records always
/// point into the image; a record outside it means the table is malformed.
fn importWord(img: *const @import("../xex/image.zig").Image, addr: u32, lib: []const u8, record: usize) !u32 {
    const off = @as(i64, addr) - @as(i64, img.base_address);
    if (off < 0 or off + 4 > img.bytes.len) {
        std.debug.print("codegen: {s} record {d} address 0x{X} is outside the image\n", .{ lib, record, addr });
        return error.ImportOutsideImage;
    }
    return std.mem.readInt(u32, img.bytes[@intCast(off)..][0..4], .big);
}

/// Returns the thunk stub address for `ordinal`, or 0 when the import is data.
fn matchingThunk(
    img: *const @import("../xex/image.zig").Image,
    addresses: []const u32,
    ordinal: u16,
    lib: []const u8,
) !u32 {
    for (addresses, 0..) |addr, record| {
        if (addr == 0) continue;
        const word = try importWord(img, addr, lib, record);
        if (word >> 24 == 1 and @as(u16, @truncate(word)) == ordinal) return addr;
    }
    return 0;
}

fn kernelCase(
    allocator: std.mem.Allocator,
    out: *std.ArrayList(u8),
    thunk: u32,
    name: []const u8,
    ordinal: u16,
) !void {
    try out.print(allocator, "        0x{X} => {{ const Seen = struct {{ var value: bool = false; }}; if (!Seen.value) {{ Seen.value = true; logImport(\"{f}\", 0x{X}, ctx); }} @import(\"rezig_runtime\").kernel.apply(\"{f}\", 0x{X}, ctx); return true; }},\n", .{
        thunk, std.zig.fmtString(name), ordinal, std.zig.fmtString(name), ordinal,
    });
}

test "kernel case escapes the library name" {
    var out = std.ArrayList(u8).empty;
    defer out.deinit(std.testing.allocator);
    try kernelCase(std.testing.allocator, &out, 0x1000, "x\"y\n", 0x10);
    try std.testing.expect(std.mem.indexOf(u8, out.items, "\\\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, out.items, "\\n") != null);
}
