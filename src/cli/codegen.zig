//! `rezig codegen`: emit Zig for selected guest functions.

const std = @import("std");
const Io = std.Io;
const parse = @import("parse.zig");
const image = @import("../xex/image.zig");
const analyze = @import("../ppc/analyze.zig");
const slice = @import("../codegen/slice.zig");
const pdata_mod = @import("../ppc/pdata.zig");
const xextool = @import("xextool");
const emit = @import("../codegen/emit.zig");
const abi = @import("../codegen/abi.zig");

pub const Options = parse.Codegen;

pub const header =
    \\// Generated by rezig. Do not edit.
    \\
    \\const std = @import("std");
    \\const Ctx = @import("rezig_runtime").ctx.Ctx;
    \\
    \\
;

fn pdataStarts(allocator: std.mem.Allocator, img: anytype) ![]u32 {
    for (img.sections) |section| {
        const n = std.mem.indexOfScalar(u8, &section.name, 0) orelse section.name.len;
        if (!std.mem.eql(u8, section.name[0..n], ".pdata")) continue;
        return pdata_mod.starts(allocator, img.sectionBytes(section));
    }
    return &.{};
}

pub fn run(allocator: std.mem.Allocator, io: Io, opts: Options, key: ?[16]u8) !void {
    const xex_path = if (opts.xex) |p|
        try allocator.dupe(u8, p)
    else
        try std.fmt.allocPrint(allocator, "{s}/default.xex", .{opts.tree.?});
    defer allocator.free(xex_path);

    var img = try image.load(allocator, io, xex_path, key);
    defer img.deinit(allocator);

    const sections = try allocator.alloc(analyze.CodeSection, img.sections.len);
    defer allocator.free(sections);
    var count: usize = 0;
    for (img.sections) |s| {
        if (!img.isExecutable(s)) continue;
        sections[count] = .{ .addr = img.base_address + s.virtual_address, .bytes = img.sectionBytes(s) };
        count += 1;
    }

    const starts = try pdataStarts(allocator, img);
    defer if (starts.len != 0) allocator.free(starts);

    const found = try analyze.functionsFrom(allocator, sections[0..count], img.entry_point, starts);
    defer analyze.freeFunctions(allocator, found);

    var picked: []slice.Candidate = undefined;
    if (opts.slice_list) |path| {
        const addrs = try slice.readAddressList(allocator, io, path);
        defer allocator.free(addrs);
        picked = try allocator.alloc(slice.Candidate, addrs.len);
        for (addrs, 0..) |addr, i| {
            var err_addr: u32 = 0;
            picked[i] = .{ .addr = addr, .words = try analyze.functionAt(allocator, sections[0..count], addr, &err_addr) };
        }
    } else if (opts.all == true) {
        var list: std.ArrayList(slice.Candidate) = .empty;
        errdefer {
            for (list.items) |c| allocator.free(c.words);
            list.deinit(allocator);
        }
        for (found) |f| {
            if (f.words.len == 0 or f.words.len > analyze.max_function_insns) continue;
            if (!emit.supportsAll(f.addr, f.words)) continue;
            const words = try allocator.dupe(u32, f.words);
            errdefer allocator.free(words);
            _ = emit.function(allocator, words, .{ .addr = f.addr, .external_dispatch = true }) catch |e| {
                std.debug.print("codegen fail addr 0x{X}: {s}\n", .{ f.addr, @errorName(e) });
                allocator.free(words);
                continue;
            };
            try list.append(allocator, .{ .addr = f.addr, .words = words });
        }
        picked = try list.toOwnedSlice(allocator);
    } else {
        const wanted = opts.slice orelse return error.MissingOption;
        picked = try slice.select(allocator, sections[0..count], img.entry_point, wanted, starts);
    }
    defer allocator.free(picked);

    if (opts.all == true) {
        const chunk_size: usize = 1000;
        var chunks: std.ArrayList([]const u8) = .empty;
        defer {
            for (chunks.items) |c| allocator.free(c);
            chunks.deinit(allocator);
        }

        var i: usize = 0;
        var index: usize = 0;
        while (i < picked.len) {
            const end = @min(i + chunk_size, picked.len);
            const chunk = picked[i..end];

            var out = std.ArrayList(u8).empty;
            errdefer out.deinit(allocator);
            try out.appendSlice(allocator, header);
            for (chunk, 0..) |candidate, j| {
                if (j != 0) try out.append(allocator, '\n');
                const text = try emit.function(allocator, candidate.words, .{ .addr = candidate.addr, .external_dispatch = true });
                defer allocator.free(text);
                try out.appendSlice(allocator, text);
            }
            try out.appendSlice(allocator, "\npub fn chunk_dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
            for (chunk) |candidate| {
                var name_buf: [10]u8 = undefined;
                try out.print(allocator, "        0x{X} => {{\n            {s}(ctx);\n            return true;\n        }},\n", .{
                    candidate.addr, abi.fnName(candidate.addr, &name_buf),
                });
            }
            try out.appendSlice(allocator, "        else => false,\n    };\n}\n");

            const name = try std.fmt.allocPrint(allocator, "chunk_{d:0>3}.zig", .{index});
            defer allocator.free(name);
            var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
            defer dir.close(io);
            var atomic = try dir.createFileAtomic(io, name, .{ .replace = true });
            defer atomic.deinit(io);
            try atomic.file.writeStreamingAll(io, out.items);
            try atomic.replace(io);
            out.deinit(allocator);

            const owned = try allocator.dupe(u8, name);
            try chunks.append(allocator, owned);

            i = end;
            index += 1;
        }

        var central = std.ArrayList(u8).empty;
        defer central.deinit(allocator);
        try central.appendSlice(allocator, "const std = @import(\"std\");\n");
        try central.appendSlice(allocator, "const Ctx = @import(\"rezig_runtime\").ctx.Ctx;\n\n");
        for (chunks.items, 0..) |name, ci| {
            try central.print(allocator, "const chunk_{d:0>3} = @import(\"{s}\");\n", .{ ci, name });
        }
        try central.appendSlice(allocator, "\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n");
        for (chunks.items, 0..) |_, ci| {
            try central.print(allocator, "    if (chunk_{d:0>3}.chunk_dispatch(addr, ctx)) return true;\n", .{ci});
        }
        try central.appendSlice(allocator, "    return @import(\"kernel.zig\").dispatch(addr, ctx);\n}\n");

        var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
        defer dir.close(io);
        var atomic = try dir.createFileAtomic(io, "dispatch.zig", .{ .replace = true });
        defer atomic.deinit(io);
        try atomic.file.writeStreamingAll(io, central.items);
        try atomic.replace(io);

        // Import thunks become host stubs that log on first call.
        var kernel = std.ArrayList(u8).empty;
        defer kernel.deinit(allocator);
        try kernel.appendSlice(allocator, "const std = @import(\"std\");\nconst Ctx = @import(\"rezig_runtime\").ctx.Ctx;\n\nfn logImport(comptime name: []const u8, comptime index: usize, ctx: *const Ctx) void {\n    std.debug.print(\"import {s}[{d}] lr=0x{X} r3=0x{X} r4=0x{X} r5=0x{X} r6=0x{X}\\n\", .{ name, index, ctx.lr, ctx.gpr[3], ctx.gpr[4], ctx.gpr[5], ctx.gpr[6] });\n}\n\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
        if (key) |k| {
            const raw = Io.Dir.cwd().readFileAlloc(io, xex_path, allocator, .limited(1 << 40)) catch null;
            if (raw) |bytes| {
                defer allocator.free(bytes);
                var xex = xextool.xex.model.Xex.init(allocator);
                defer xex.deinit();
                const keys = xextool.xex.keys.Keys.uniform(k);
                if (xextool.xex.reader.readBytes(&xex, bytes, keys)) |_| {} else |_| {}
                for (xex.import_libraries.items) |lib| {
                    const name = std.mem.sliceTo(&lib.name, 0);
                    for (lib.addresses, 0..) |thunk, oi| {
                        if (thunk == 0) continue;
                        try kernel.print(allocator, "        0x{X} => {{ logImport(\"{s}\", {d}, ctx); return true; }},\n", .{ thunk, name, oi });
                    }
                }
            }
        }
        try kernel.appendSlice(allocator, "        else => false,\n    };\n}\n");
        var kernel_atomic = try dir.createFileAtomic(io, "kernel.zig", .{ .replace = true });
        defer kernel_atomic.deinit(io);
        try kernel_atomic.file.writeStreamingAll(io, kernel.items);
        try kernel_atomic.replace(io);

        var addr_list = try allocator.alloc(u32, picked.len);
        defer allocator.free(addr_list);
        for (picked, 0..) |candidate, j| addr_list[j] = candidate.addr;
        var list_buf: [512]u8 = undefined;
        const list_path = try std.fmt.bufPrint(&list_buf, "{s}/addresses.json", .{opts.out});
        try slice.writeAddressList(allocator, io, list_path, addr_list);

        var buf: [256]u8 = undefined;
        var writer = Io.File.stdout().writer(io, &buf);
        try writer.interface.print("emitted {d} functions in {d} chunks to {s}\n", .{ picked.len, chunks.items.len, opts.out });
        try writer.interface.flush();
        return;
    }

    var out = std.ArrayList(u8).empty;
    defer out.deinit(allocator);
    try out.appendSlice(allocator, header);
    for (picked, 0..) |candidate, i| {
        if (i != 0) try out.append(allocator, '\n');
        const text = try emit.function(allocator, candidate.words, .{ .addr = candidate.addr });
        defer allocator.free(text);
        try out.appendSlice(allocator, text);
    }

    for (picked) |candidate| {
        try out.print(allocator, "const w_{X} = [_]u32{{\n", .{candidate.addr});
        for (candidate.words, 0..) |word, i| {
            if (i % 4 == 0) try out.appendSlice(allocator, "    ");
            try out.print(allocator, "0x{X}", .{word});
            if (i + 1 == candidate.words.len) {
                try out.appendSlice(allocator, ",\n");
            } else if (i % 4 == 3) {
                try out.appendSlice(allocator, ",\n");
            } else {
                try out.appendSlice(allocator, ", ");
            }
        }
        try out.appendSlice(allocator, "};\n");
    }
    try out.appendSlice(allocator, "\npub const functions = [_]struct { addr: u32, words: []const u32 }{\n");
    for (picked) |candidate| {
        try out.print(allocator, "    .{{ .addr = 0x{X}, .words = &w_{X} }},\n", .{ candidate.addr, candidate.addr });
    }
    try out.appendSlice(allocator, "};\n\npub fn dispatch(addr: u32, ctx: *Ctx) bool {\n    return switch (addr) {\n");
    for (picked) |candidate| {
        var name_buf: [10]u8 = undefined;
        try out.print(allocator, "        0x{X} => {{\n            {s}(ctx);\n            return true;\n        }},\n", .{ candidate.addr, abi.fnName(candidate.addr, &name_buf) });
    }
    try out.appendSlice(allocator, "        else => false,\n    };\n}\n");

    var dir = try Io.Dir.cwd().createDirPathOpen(io, opts.out, .{});
    defer dir.close(io);
    var atomic = try dir.createFileAtomic(io, "slice.zig", .{ .replace = true });
    defer atomic.deinit(io);
    try atomic.file.writeStreamingAll(io, out.items);
    try atomic.replace(io);

    var addr_list = try allocator.alloc(u32, picked.len);
    defer allocator.free(addr_list);
    for (picked, 0..) |candidate, i| addr_list[i] = candidate.addr;
    var list_buf: [512]u8 = undefined;
    const list_path = try std.fmt.bufPrint(&list_buf, "{s}/addresses.json", .{opts.out});
    try slice.writeAddressList(allocator, io, list_path, addr_list);

    var buf: [256]u8 = undefined;
    var writer = Io.File.stdout().writer(io, &buf);
    try writer.interface.print("emitted {d} functions to {s}/slice.zig\n", .{ picked.len, opts.out });
    try writer.interface.flush();
}
